  // Where the site lives, from this script's own address, so the apps (/oak/, /birch/, /sequoia/) and the page share one path.
  var ROOT = (function () { try { var s = document.currentScript && document.currentScript.src; if (s) return new URL('..', s).href.replace(/\/$/, ''); } catch (e) {} return location.origin; })();
  var READ = '/read.js?v=b813', LEARN = '/shared/gg-learn.js?v=b839';
  var ACC = '#4E7D6A';
  var esc = function (x) { return String(x == null ? '' : x).replace(/[&<>"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; }); };
  function need(src, test) { return new Promise(function (ok) { if (test()) return ok(); var s = document.createElement('script'); s.src = ROOT + src; s.onload = s.onerror = function () { ok(); }; document.head.appendChild(s); }); }
  function ready() { return need(READ, function () { return !!window.GGRead; }).then(function () { return need(LEARN, function () { return !!window.GGLearn; }); }).then(function () { if (!window.GGLearn) throw new Error('gg-learn did not load'); }); }
  function lesson(n) { n = parseInt(n, 10); return D.lessons[n - 1] || null; }
  var track = D.track; track.lessons = D.lessons;

  // Play day n in the shared player, inside host (an element the caller owns). Resolves the player's controller.
  // opts: app ('site'), accent, done ({id: 1}), onDone(n, id), onEnd(button, n), home(), backLabel, mark, mood.
  function play(host, n, opts) {
    opts = opts || {};
    var l = lesson(n); if (!l || !host) return Promise.reject(new Error('no day ' + n));
    return ready().then(function () {
      var nx = lesson(l.n + 1), done = opts.done || {}, e = l.ending, btns = [];
      if (nx) btns.push(['next', 'Day ' + nx.n + ': ' + nx.title, 'pri']);
      btns.push(['again', 'Watch Again', nx ? '' : 'pri']);
      btns.push(['back', opts.backLabel || 'Back to Early Days', 'quiet']);
      var ctl = GGLearn.player(host, {
        app: opts.app || 'site', lesson: l, track: track, tracks: [track], done: done, at: 0, accent: opts.accent || ACC,
        mood: opts.mood || 'calm', mark: opts.mark || { name: 'Living Sober' },
        ending: { eyebrow: e.eyebrow, h: e.h, sub: e.sub, say: e.say, ok: true, buttons: btns },
        onDone: function (id) { done[id] = 1; if (opts.onDone) try { opts.onDone(l.n, id); } catch (x) {} },
        onEnd: function (b) {
          if (opts.onEnd && opts.onEnd(b, l.n) === false) return; // the caller handled it
          if (b === 'next' && nx) play(host, nx.n, opts);
          else if (b === 'back') { if (opts.home) opts.home(); else close(); }
        },
        open: function () {}, home: function () { if (opts.home) opts.home(); else close(); }
      });
      if (opts.onPlay) try { opts.onPlay(l.n, ctl); } catch (x) {}
      return ctl;
    });
  }

  // Open day n in the player's own overlay (the page video look). Escape or Back closes it.
  var OV = null;
  function onKey(e) { if (OV && e.key === 'Escape') { e.preventDefault(); close(); } }
  function close() {
    if (!OV) return; var o = OV; OV = null;
    try { if (o.ctl) o.ctl.stop(); } catch (e) {}
    document.removeEventListener('keydown', onKey, true);
    o.root.remove(); document.body.style.overflow = o.overflow || '';
    if (o.from && o.from.focus) try { o.from.focus(); } catch (e) {}
  }
  function open(n, opts) {
    opts = opts || {};
    var l = lesson(n); if (!l) return Promise.reject(new Error('no day ' + n));
    var from = OV ? OV.from : document.activeElement;
    return ready().then(function () {
      if (OV) { try { OV.ctl.stop(); } catch (e) {} OV.root.remove(); document.removeEventListener('keydown', onKey, true); }
      GGLearn.css();
      var root = document.createElement('div');
      root.className = 'ggl ggl-app gg-s30'; root.setAttribute('role', 'dialog'); root.setAttribute('aria-modal', 'true'); root.setAttribute('aria-label', 'Video: Day ' + l.n + ', ' + l.title);
      root.style.setProperty('--ggl-acc', opts.accent || ACC); root.style.setProperty('--ggl-bar', '#1F3229'); root.style.setProperty('--ggl-lite', '#CFE3D8');
      root.innerHTML = '<div class="ggl-top"><img src="' + ROOT + '/favicon.svg" alt=""><b>' + esc(D.title) + '</b><button type="button" class="ggl-x" data-s30-x="1">' + esc(opts.closeLabel || 'Close') + '</button></div>'
        + '<div class="ggl-in"><div class="ggl-eb">Early Days, Day ' + l.n + ' of ' + D.count + '</div><h1 tabindex="-1">' + esc(l.title) + '</h1><p class="ggl-muted">' + esc(l.blurb) + ' About ' + l.mins + (l.mins === 1 ? ' minute.' : ' minutes.') + '</p><div class="gg-s30-host"></div></div>';
      document.body.appendChild(root);
      OV = { root: root, from: from, overflow: OV ? OV.overflow : document.body.style.overflow, ctl: null };
      document.body.style.overflow = 'hidden';
      document.addEventListener('keydown', onKey, true);
      root.addEventListener('click', function (e) { if (e.target.closest('[data-s30-x]')) close(); });
      var o = {}; for (var k in opts) o[k] = opts[k];
      o.backLabel = opts.backLabel || 'Close';
      o.onEnd = function (b, day) {
        if (opts.onEnd && opts.onEnd(b, day) === false) return false;
        if (b === 'next' && lesson(day + 1)) { open(day + 1, opts); return false; }
        if (b === 'back') { close(); return false; }
      };
      o.home = close;
      return play(root.querySelector('.gg-s30-host'), l.n, o).then(function (ctl) {
        if (OV && OV.root === root) OV.ctl = ctl;
        var h = root.querySelector('h1'); if (h) try { h.focus({ preventScroll: true }); } catch (e) {}
        return ctl;
      });
    });
  }
  // Which day to show: days since the sober date (day 1 on the date itself), capped at 30; 1 without a date.
  function dayFor(soberDate, now) {
    if (!soberDate) return 1;
    var d = new Date(String(soberDate).slice(0, 10) + 'T00:00:00'), t = now ? new Date(now) : new Date();
    if (isNaN(d)) return 1;
    t.setHours(0, 0, 0, 0);
    var n = Math.floor((t - d) / 86400000) + 1;
    return Math.max(1, Math.min(D.count, n));
  }
  D.lesson = lesson; D.play = play; D.open = open; D.close = close; D.dayFor = dayFor; D.ready = ready;
  window.GGSober30 = D;
